"""
baseline.py -- a check whose backlog is not zero cannot signal a new violation.

WHY THIS EXISTS.  A suite of checks run over a project that has grown under weaker rules
returns rows -- hundreds of them -- from the first run onward.  For a check with a standing
backlog, a row returned tomorrow cannot be told from the rows returned today, so the check
reports and nothing in the report is a signal.  The fix is not to clear the backlog
silently but to record it, so that every later run can say which of its rows are new.

WHAT IT DOES.  It records the STANDING ROWS as identities and lets `run.py` split a check's
output into HELD and NEW.

  A ROW IDENTITY is (check, kind, file basename, line).  It is deliberately tight: a row
  that moves to another line is reported as new, because a file whose lines moved is a
  file somebody just touched and its rows are worth reading again.

  THE RECORD is registers/BASELINE.md, one row per line, pipe-separated, sorted.  It is
  text so that it diffs, greps and is cited like anything else in the project.

  REGENERATION IS AN ACT, never automatic: `python3 -m discipline.baseline --write` at a
  reassessment point, over the space.  A silent auto-refresh would restore exactly the
  condition this module exists to remove.

WHAT IT DOES NOT DO.  It does not clear anything.  A held row is still a row and still in
the report under its check; the backlog is worked down by fixing files, and the record
shrinks when it is regenerated after that.

Rows, not counts.
"""
import re, sys, os
from pathlib import Path
import sys as _s, os as _o; _s.path.insert(0, _o.path.dirname(_o.path.abspath(__file__)))
import config

HERE = Path(__file__).resolve().parent
KIND = re.compile(r"^\s{2}([a-z][A-Za-z-]{3,})\s+(\S*[./]\S*?)(?::(\d+))?\s")
SENSE = re.compile(r"^==\s+(.+?)\s+\((\d+) definitional lines, (\d+) sense-groups\)")
HEADER = "# BASELINE -- the rows standing in the suite when it was last regenerated.\n" \
         "# check | kind | file | line.  Regenerated by hand at a reassessment point:\n" \
         "#   python3 -m discipline.baseline --write\n"


def record_path(start=None):
    return config.registers(start) / "BASELINE.md"


def identities(check, text):
    """the row identities a check's printed output carries."""
    out = []
    for line in text.split("\n"):
        m = KIND.match(line)
        if m:
            kind, where, ln = m.group(1), m.group(2), m.group(3) or "-"
            out.append((check, kind, os.path.basename(where), ln))
            continue
        m = SENSE.match(line)
        if m and int(m.group(3)) > 1:
            out.append((check, "multi-sense", m.group(1).strip(), "-"))
    return out


def load(path=None):
    p = Path(path) if path else record_path()
    held = set()
    if not p.is_file():
        return held
    for line in p.read_text(errors="replace").split("\n"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = [x.strip() for x in line.split("|")]
        if len(parts) == 4:
            held.add(tuple(parts))
    return held


def write(keys, path=None):
    p = Path(path) if path else record_path()
    p.parent.mkdir(parents=True, exist_ok=True)
    body = "\n".join(" | ".join(k) for k in sorted(keys))
    p.write_text(HEADER + body + "\n")
    return len(keys)


def split(check, text, held):
    """(held rows, new rows) for one check's output."""
    ids = identities(check, text)
    return ([i for i in ids if i in held], [i for i in ids if i not in held])


def main(argv):
    if "--write" not in argv:
        held = load()
        print("baseline: %d row identities on record (%s)" % (len(held), record_path().name))
        return 0
    sys.path.insert(0, str(HERE))
    import io, contextlib
    import predeclare, rowsplit, guard, withdraw, noliteral, names, forced, cited
    import ground, primitive
    root = config.space()
    files = sorted(str(f) for f in root.glob(config.glob_pattern()))
    reg = str(config.registers(root) / "NAMES.md")
    suite = [("predeclare", lambda a: predeclare.check(a)),
             ("rowsplit", lambda a: rowsplit.lint(a)),
             ("guard", lambda a: guard.lint(a)),
             ("withdraw", lambda a: withdraw.check(a)),
             ("noliteral", lambda a: noliteral.main(a)),
             ("names", lambda a: names.main(["--names", reg] + a)),
             ("forced", lambda a: forced.check(a)),
             ("cited", lambda a: cited.check(a)),
             ("ground", lambda a: ground.check(a)),
             ("primitive", lambda a: primitive.check(a))]
    keys = set()
    for (nm, fn) in suite:
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            fn(list(files))
        got = identities(nm, buf.getvalue())
        keys |= set(got)
        print("  %-12s %5d row identities" % (nm, len(got)))
    n = write(keys)
    print("baseline: %d row identities written to %s over %d files" % (n, record_path().name, len(files)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
